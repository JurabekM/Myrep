def shared_keys(arb: dict[str, str]) -> list[str]:
    def keep(k: str) -> bool:
        if k.startswith("@") or k in {"sessionKind", "reasonOther", "role"}:
            return False
        return k == "disclaimer" or k.startswith(("verdict", "type", "sessionKind", "reason", "kind", "role"))

    return [k for k in arb if keep(k)]


def dart_string(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def render() -> str:
    uz = json.loads((ARB / "app_uz.arb").read_text(encoding="utf-8"))
    ru = json.loads((ARB / "app_ru.arb").read_text(encoding="utf-8"))
    keys = shared_keys(uz)
    lines = [
        "// GENERATED by tool/gen_strings.py from app/lib/l10n/app_{uz,ru}.arb — qo'lda tahrirlanmaydi.",
        "",
        "/// PDF protokol matnlari (uz — standart, ru). `pdf.*` — faqat PDF uchun.",
        "const Map<String, Map<String, String>> pdfStrings = {",
    ]
    for loc, src, idx in (("uz", uz, 0), ("ru", ru, 1)):
        lines.append(f"  '{loc}': {{")
        lines += [f"    '{k}': {dart_string(src[k])}," for k in keys]
        lines += [f"    'pdf.{k}': {dart_string(v[idx])}," for k, v in PDF_ONLY.items()]
        lines.append("  },")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.name} eskirgan — python3 -I tool/gen_strings.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
