"""osv_audit.py — tarmoqsiz testlar (lock-fayl tahlili va istisno muddati)."""

from __future__ import annotations

import tempfile
import unittest
from datetime import date, timedelta
from pathlib import Path
from unittest import mock

import osv_audit

PUB = """# Generated by pub
packages:
  async:
    dependency: transitive
    description:
      name: async
      sha256: "abc"
      url: "https://pub.dev"
    source: hosted
    version: "2.13.0"
  zanjir_core:
    dependency: "direct main"
    description:
      path: "../zanjir_core"
      relative: true
    source: path
    version: "0.1.0"
  http:
    dependency: "direct main"
    description:
      name: http
      url: "https://pub.dev"
    source: hosted
    version: "1.6.0"
sdks:
  dart: ">=3.13.0 <4.0.0"
"""

UV = """version = 1
[[package]]
name = "jinja2"
version = "3.1.6"
source = { registry = "https://pypi.org/simple" }

[[package]]
name = "zanjir-server"
version = "0.1.0"
source = { editable = "." }
"""


class ParseTest(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = tempfile.TemporaryDirectory()
        root = Path(self.tmp.name)
        (root / "pubspec.lock").write_text(PUB, encoding="utf-8")
        (root / "uv.lock").write_text(UV, encoding="utf-8")
        self.patch = mock.patch.object(osv_audit, "ROOT", root)
        self.patch.start()
        self.root = root

    def tearDown(self) -> None:
        self.patch.stop()
        self.tmp.cleanup()

    def test_pub_only_hosted(self) -> None:
        pkgs = osv_audit.pub_packages(self.root / "pubspec.lock")
        self.assertEqual([(p.name, p.version) for p in pkgs], [("async", "2.13.0"), ("http", "1.6.0")])
        self.assertTrue(all(p.ecosystem == "Pub" for p in pkgs))

    def test_uv_only_registry(self) -> None:
        pkgs = osv_audit.uv_packages(self.root / "uv.lock")
        self.assertEqual([(p.ecosystem, p.name, p.version) for p in pkgs], [("PyPI", "jinja2", "3.1.6")])


class AllowlistTest(unittest.TestCase):
    def test_expiry(self) -> None:
        finding = {"id": "GHSA-x", "aliases": ["CVE-1"]}
        future = (date.today() + timedelta(days=1)).isoformat()
        past = (date.today() - timedelta(days=1)).isoformat()
        self.assertTrue(osv_audit.allowlisted(finding, [{"id": "CVE-1", "until": future, "reason": "x"}]))
        self.assertFalse(osv_audit.allowlisted(finding, [{"id": "CVE-1", "until": past, "reason": "x"}]))
        self.assertFalse(osv_audit.allowlisted(finding, []))


if __name__ == "__main__":
    unittest.main()
